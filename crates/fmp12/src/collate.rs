fn weights(c: char) -> Option<(&'static [u16], &'static [u8], &'static [u8])> {
    let i = WEIGHTS.binary_search_by_key(&c, |w| w.0).ok()?;
    let (_, p, s, t) = WEIGHTS[i];
    Some((p, s, t))
}

/// Collation key of `name` (key of the catalogs' name index `[cat].[1].[1]`),
/// or `None` when it holds a character whose weights are unknown.
pub fn name_key(name: &str) -> Option<Vec<u8>> {
    let mut p = Vec::new();
    let (mut s, mut t) = (Vec::new(), Vec::new());
    let (mut any_s, mut any_t) = (false, false);
    for c in name.chars() {
        let (cp, cs, ct) = weights(c)?;
        let n = cs.len().max(ct.len()).max(cp.len());
        p.extend(cp.iter().flat_map(|w| w.to_be_bytes()));
        any_s |= !cs.is_empty();
        any_t |= !ct.is_empty();
        s.extend(if cs.is_empty() {
            vec![1; n]
        } else {
            cs.to_vec()
        });
        t.extend(if ct.is_empty() {
            vec![1; n]
        } else {
            ct.to_vec()
        });
    }
    p.extend([0, 0]);
    if any_s {
        p.extend(s);
    }
    p.push(0);
    if any_t {
        p.extend(t);
    }
    Some(p)
}

/// Key of a field in the field catalog's second index `[T].[3].[1].[6]`:
/// field type, data type × 4 (+1 when global), then the name key without
/// its tertiary part.
pub fn field_type_key(kind: u8, data_type: u8, global: bool, name: &str) -> Option<Vec<u8>> {
    let k = name_key(name)?;
    // Primary weights end at the first 00 00 on an even offset.
    let mut i = 0;
    while k.get(i..i + 2)? != [0, 0] {
        i += 2;
    }
    let end = i + 2 + k[i + 2..].iter().position(|b| *b == 0)?;
    let mut out = vec![kind, data_type * 4 + global as u8];
    out.extend_from_slice(&k[..end]);
    Some(out)
}

#[cfg(test)]
mod tests {
    use super::*;

    fn hex(b: &[u8]) -> String {
        b.iter().map(|x| format!("{x:02x}")).collect()
    }

    #[test]
    fn keys_match_filemaker() {
        // Name indexes of a new file made by FileMaker Pro 26 (French UI).
        assert_eq!(
            hex(&name_key("Blank").unwrap()),
            "12251330120f136d131e000000"
        );
        assert_eq!(hex(&name_key("T2").unwrap()), "14331207000000");
        assert_eq!(
            hex(&name_key("Clé primaire").unwrap()),
            "123d1330126b020a13b313da12ec135f120f12ec13da126b00000101011301010101010101010100"
        );
        // Fraction: three primary weights and tertiary weights.
        assert_eq!(
            hex(&name_key("x¼").unwrap()),
            "14971206035d1209000000011d1d1e"
        );
        assert_eq!(name_key("漢"), None);
        assert_eq!(
            hex(&field_type_key(1, 1, false, "Clé primaire").unwrap()),
            "0104123d1330126b020a13b313da12ec135f120f12ec13da126b000001010113010101010101010101"
        );
        assert_eq!(
            hex(&field_type_key(1, 1, true, "G").unwrap()),
            "010512b00000"
        );
    }
}
