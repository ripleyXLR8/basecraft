setvar("$$e", '"|"')
path_step(190, F); log("create")
path_step(191, F, "$id"); log("open", "$id")
setvar("$d", '"abcdef"')
raw(f"step 192 opt=4005 arg=2 {V}"); raw("text 32 $d"); raw("calc 0 $id"); log("w")
id_step(194, target="$x", calcs=["$id"]); log("pos", "$x")
id_step(195, calcs=["$id", "0"]); log("set0")
id_step(194, target="$x", calcs=["$id"]); log("pos", "$x")
id_step(193, arg=2, target="$r1", calcs=["$id", "2"]); log("r1", "$r1")
id_step(194, target="$x", calcs=["$id"]); log("pos", "$x")
id_step(193, arg=2, target="$r2", calcs=["$id"]); log("r2", "$r2")
id_step(194, target="$x", calcs=["$id"]); log("pos", "$x")
id_step(195, calcs=["$id", "1"]); log("set1")
id_step(194, target="$x", calcs=["$id"]); log("pos", "$x")
id_step(193, arg=2, target="$r3", calcs=["$id", "2"]); log("r3", "$r3")
id_step(193, arg=2, target="$r3b", calcs=["$id", None, "2"]); log("r3b", "$r3b")
id_step(195, calcs=["$id", "100"]); log("set100")
id_step(194, target="$x", calcs=["$id"]); log("pos", "$x")
id_step(193, arg=2, target="$r4", calcs=["$id", "1"]); log("reof", '"[" & $r4 & "]"')
id_step(195, calcs=["$id", "-1"]); log("setneg")
id_step(194, target="$x", calcs=["$id"]); log("pos", "$x")
id_step(195, calcs=["$id", "0"]); log("set0")
id_step(193, arg=1, target="$r5", calcs=["$id", "1"]); log("r16", 'Length ( $r5 ) & "/" & Code ( $r5 )')
id_step(194, target="$x", calcs=["$id"]); log("pos", "$x")
id_step(195, calcs=["$id", "0"]); log("set0")
id_step(193, arg=3, target="$r6", calcs=["$id", "3"]); log("rbytes", 'GetContainerAttribute ( $r6 ; "fileSize" ) & "/" & GetAsText ( $r6 )')
id_step(194, target="$x", calcs=["$id"]); log("pos", "$x")
id_step(195, calcs=["$id", "6"]); log("setend")
setvar("$d", '"é¶x"')
raw(f"step 192 opt=4005 arg=1 {V}"); raw("text 32 $d"); raw("calc 0 $id"); log("w16")
id_step(194, target="$x", calcs=["$id"]); log("pos", "$x")
id_step(195, calcs=["$id", "6"]); log("set6")
id_step(193, arg=1, target="$r7", calcs=["$id"]); log("r16all", 'Length ( $r7 ) & "/" & Code ( $r7 )')
id_step(195, calcs=["$id", "0"]); log("set0")
id_step(193, arg=2, target="$r8", calcs=["$id", "7"]); log("r8", 'Length ( $r8 ) & "/" & Code ( $r8 )')
id_step(196, calcs=["$id"]); log("close")
path_step(189, F, "$x"); log("size", "$x")
path_step(197, F); log("del")
# Folders.
path_step(190, "file:bc_sub/x.txt", opt=0x220); log("createdirs")
path_step(188, "file:bc_sub/x.txt", "$x"); log("gfe", "$x")
setvar("$p", 'Substitute ( Get ( FilePath ) ; Get ( FileName ) & ".fmp12" ; "bc_sub2/y.txt" )')
log("p", "$p")
path_step(190, "$p", opt=0x220); log("createdirsabs")
path_step(188, "$p", "$x"); log("gfeabs", "$x")
setvar("$p", 'Substitute ( Get ( FilePath ) ; Get ( FileName ) & ".fmp12" ; "bc_sub2" )')
path_step(188, "$p", "$x"); log("gfedir", "$x")
path_step(189, "$p", "$x"); log("gfsdir", "$x")
setvar("$p", '"file:bc_nope.txt¶file:bc_s3.txt"')
path_step(190, "file:bc_s3.txt"); log("c3")
path_step(188, "$p", "$x"); log("gfelist", "$x")
