raw("step 228 opt=4000 arg=1"); raw('calc 0 "999"'); log("golistbad", 'Get ( FoundCount )')
raw("step 228 opt=4000 arg=1"); raw('calc 0 ""'); log("golistempty", 'Get ( FoundCount )')
raw("step 228 opt=4000 arg=1"); raw('calc 0 GetValue ( $ids ; 1 ) & "¶" & GetValue ( $ids ; 1 )'); log("golistdup", 'Get ( FoundCount )')
finish()
